// Supabase Storage REST helper for Cloudflare Workers.
// Scaffold only: call these helpers ONLY after implementing authentication,
// authorization, file validation, rate limiting, and order ownership checks.
// Never expose SUPABASE_SERVICE_ROLE_KEY to browser code.

function storageHeaders(env) {
  if (!env.SUPABASE_URL || !env.SUPABASE_SERVICE_ROLE_KEY) {
    throw new Error("Supabase Storage is not configured");
  }
  return {
    apikey: env.SUPABASE_SERVICE_ROLE_KEY,
    Authorization: `Bearer ${env.SUPABASE_SERVICE_ROLE_KEY}`,
    "Content-Type": "application/json"
  };
}

export async function createSignedUploadUrl(env, bucket, objectPath) {
  // objectPath must be generated by the server, not accepted as an arbitrary
  // client path. Example: receipts/<order-id>/<random-id>.jpg
  const url = `${env.SUPABASE_URL}/storage/v1/object/upload/sign/${encodeURIComponent(bucket)}/${objectPath
    .split("/")
    .map(encodeURIComponent)
    .join("/")}`;

  const response = await fetch(url, {
    method: "POST",
    headers: storageHeaders(env),
    body: JSON.stringify({})
  });

  if (!response.ok) {
    throw new Error(`Supabase signed upload URL failed: ${response.status}`);
  }
  return response.json();
}

export async function createSignedDownloadUrl(env, bucket, objectPath, expiresIn = 120) {
  const url = `${env.SUPABASE_URL}/storage/v1/object/sign/${encodeURIComponent(bucket)}/${objectPath
    .split("/")
    .map(encodeURIComponent)
    .join("/")}`;

  const response = await fetch(url, {
    method: "POST",
    headers: storageHeaders(env),
    body: JSON.stringify({ expiresIn })
  });

  if (!response.ok) {
    throw new Error(`Supabase signed download URL failed: ${response.status}`);
  }
  return response.json();
}
